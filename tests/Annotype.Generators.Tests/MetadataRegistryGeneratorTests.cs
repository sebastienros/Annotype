    [Fact]
    public void GeneratesExpectedRegistryForPaymentPlugin()
    {
        var run = Generate("""
            using Payments.Contracts;

            [PluginMetadata("payments", Priority = 10)]
            public sealed class PaymentPlugin : IPlugin
            {
            }
            """);

        Assert.Empty(run.Diagnostics);
        TestCompilation.AssertClean(run.Output);

        var version = typeof(MetadataRegistryGenerator).Assembly.GetName().Version;
        Assert.Equal($$"""
            // <auto-generated/>
            // Generated by the Annotype source generator. Do not edit.

            namespace Annotype.Generated.Payments_Plugins
            {
                /// <summary>
                /// Reflection-free metadata registry of this assembly. Register it with
                /// <c>global::Annotype.Metadata.Register(MetadataRegistry.Instance)</c>.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("Annotype", "{{version}}")]
                public sealed class MetadataRegistry : global::Annotype.IMetadataRegistry
                {
                    private MetadataRegistry()
                    {
                    }

                    /// <summary>Gets the registry instance.</summary>
                    public static MetadataRegistry Instance { get; } = new MetadataRegistry();

                    /// <inheritdoc />
                    public bool TryGet(global::System.Type implementationType, global::System.Type attributeType, out global::System.Attribute metadata)
                    {
                        if (implementationType == typeof(global::PaymentPlugin))
                        {
                            if (attributeType == typeof(global::Payments.Contracts.PluginMetadataAttribute))
                            {
                                metadata = new global::Payments.Contracts.PluginMetadataAttribute("payments") { Priority = 10 };
                                return true;
                            }

                            metadata = null;
                            return false;
                        }

                        metadata = null;
                        return false;
                    }
                }
            }

            """.ReplaceLineEndings("\n"), run.Source);
    }

