    public void SupportedValuesRoundTrip(string typeName)
    {
        var compilation = TestCompilation.Create([ValueContracts, ValueImplementations], "Values.RoundTrip");
        var run = TestCompilation.RunGenerator(compilation);
        Assert.Empty(run.Diagnostics);
        TestCompilation.AssertClean(run.Output);

        var assembly = TestCompilation.Load(run.Output);
        var registry = TestCompilation.GetRegistry(assembly, "Annotype.Generated.Values_RoundTrip");
        var implementation = assembly.GetType(typeName, throwOnError: true)!;
        var attributeType = assembly.GetType("Values.ValuesAttribute", throwOnError: true)!;

        Assert.True(registry.TryGet(implementation, attributeType, out var generated));

        // The runtime's own attribute materialization is the oracle (tests only; the registry never uses it).
        var expected = implementation.GetCustomAttribute(attributeType, inherit: false)!;
        AssertAttributeEqual(expected, generated);
    }

    private static void AssertAttributeEqual(Attribute expected, Attribute actual)
    {
        Assert.Equal(expected.GetType(), actual.GetType());

        foreach (var property in expected.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.Name == nameof(Attribute.TypeId))
            {
                continue;
            }

            AssertValueEqual(property.GetValue(expected), property.GetValue(actual), property.Name);
        }

        foreach (var field in expected.GetType().GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            AssertValueEqual(field.GetValue(expected), field.GetValue(actual), field.Name);
        }
    }

    private static void AssertValueEqual(object? expected, object? actual, string member)
    {
        switch (expected)
        {
            case double d:
                Assert.Equal(BitConverter.DoubleToInt64Bits(d), BitConverter.DoubleToInt64Bits(Assert.IsType<double>(actual)));
                break;
            case float f:
                Assert.Equal(BitConverter.SingleToInt32Bits(f), BitConverter.SingleToInt32Bits(Assert.IsType<float>(actual)));
                break;
            case IList list when expected is not string:
                var actualList = Assert.IsAssignableFrom<IList>(actual);
                Assert.Equal(expected.GetType(), actual!.GetType());
                Assert.Equal(list.Count, actualList.Count);

                for (var i = 0; i < list.Count; i++)
                {
                    AssertValueEqual(list[i], actualList[i], $"{member}[{i}]");
                }

                break;
            default:
                Assert.True(Equals(expected, actual), $"{member}: expected '{expected}' ({expected?.GetType()}), actual '{actual}' ({actual?.GetType()})");
                if (expected is not null)
                {
                    Assert.Equal(expected.GetType(), actual!.GetType());
                }

                break;
        }
    }

