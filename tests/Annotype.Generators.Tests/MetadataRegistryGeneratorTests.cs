    [Fact]
    public void RepeatedRunsProduceIdenticalOutputRegardlessOfSourceOrder()
    {
        string[] sources =
        [
            Contracts,
            """
            [Payments.Contracts.PluginMetadata("b")]
            public sealed class B : Payments.Contracts.IPlugin { }
            """,
            """
            namespace A
            {
                [Payments.Contracts.PluginMetadata("a")]
                public sealed class First : Payments.Contracts.IPlugin { }
            }
            """,
            """
            [Payments.Contracts.PluginMetadata("c")]
            public sealed class C : Payments.Contracts.IPlugin { }
            """,
        ];

        var first = TestCompilation.RunGenerator(TestCompilation.Create(sources, "Determinism")).Source;
        var second = TestCompilation.RunGenerator(TestCompilation.Create(sources, "Determinism")).Source;
        var reversed = TestCompilation.RunGenerator(TestCompilation.Create([.. sources.Reverse()], "Determinism")).Source;

        Assert.NotNull(first);
        Assert.Equal(first, second);
        Assert.Equal(first, reversed);
        Assert.True(first.IndexOf("global::A.First", StringComparison.Ordinal) < first.IndexOf("global::B", StringComparison.Ordinal));
        Assert.True(first.IndexOf("global::B", StringComparison.Ordinal) < first.IndexOf("global::C", StringComparison.Ordinal));
    }

    [Fact]
