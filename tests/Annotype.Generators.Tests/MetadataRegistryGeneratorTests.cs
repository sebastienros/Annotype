    [Fact]
    public void RegistryIdentifierHashesLossyNamesToAvoidCollisions()
    {
        var dotted = RegistryNaming.GetIdentifier("Payments.Plugins");
        var underscored = RegistryNaming.GetIdentifier("Payments_Plugins");
        var dashed = RegistryNaming.GetIdentifier("Payments-Plugins");

        Assert.Equal(3, new[] { dotted, underscored, dashed }.Distinct().Count());
        Assert.StartsWith("Payments_Plugins_", underscored, StringComparison.Ordinal);
        Assert.Equal(underscored, RegistryNaming.GetIdentifier("Payments_Plugins"));
        Assert.True(SyntaxFacts.IsValidIdentifier(dashed));
    }
