    [Fact]
    public void ConstructorArgumentStringsAreEscapedAndRoundTrip()
    {
        const string text = "q\"b\\n\n t\t z\0 \u00e9 \U0001F600 \ud800 \u2028 end";
        var compilation = TestCompilation.Create([Contracts, """
            using Payments.Contracts;

            [PluginMetadata("q\"b\\n\n t\t z\0 \u00e9 \U0001F600 \ud800 \u2028 end", Priority = -1)]
            public sealed class Escaped : IPlugin { }
            """], "Escaping");
        var run = TestCompilation.RunGenerator(compilation);
        TestCompilation.AssertClean(run.Output);

        var assembly = TestCompilation.Load(run.Output);
        var registry = TestCompilation.GetRegistry(assembly, "Annotype.Generated.Escaping");
        var attributeType = assembly.GetType("Payments.Contracts.PluginMetadataAttribute")!;

        Assert.True(registry.TryGet(assembly.GetType("Escaped")!, attributeType, out var metadata));
        Assert.Equal(text, attributeType.GetProperty("Name")!.GetValue(metadata));
        Assert.Equal(-1, attributeType.GetProperty("Priority")!.GetValue(metadata));
    }

