    [Fact]
    public void NamespacedNestedAndAliasedImplementationsUseGlobalNames()
    {
        var compilation = TestCompilation.Create([Contracts, """
            using C = Payments.Contracts;

            namespace Payments
            {
                // Types that would shadow unqualified names in generated code.
                public class System { }
                public class Annotype { }
                public class MetadataRegistry { }
            }

            namespace Deep.Name.Space
            {
                public class Outer
                {
                    [C.PluginMetadata("inner", Priority = 1)]
                    public sealed class Inner : C.IPlugin { }

                    public class Middle
                    {
                        [C.PluginMetadata("deepest", Priority = 2)]
                        internal sealed class Deepest : C.IPlugin { }
                    }
                }
            }

            namespace @class
            {
                [C.PluginMetadata("keyword", Priority = 3)]
                public sealed class @event : C.IPlugin { }
            }

            [C.PluginMetadata("global", Priority = 4)]
            public sealed class GlobalPlugin : C.IPlugin { }
            """], "Nested.Types");

        var run = TestCompilation.RunGenerator(compilation);
        Assert.Empty(run.Diagnostics);
        TestCompilation.AssertClean(run.Output);
        Assert.Contains("typeof(global::Deep.Name.Space.Outer.Middle.Deepest)", run.Source, StringComparison.Ordinal);
        Assert.Contains("typeof(global::@class.@event)", run.Source, StringComparison.Ordinal);

        var assembly = TestCompilation.Load(run.Output);
        var registry = TestCompilation.GetRegistry(assembly, "Annotype.Generated.Nested_Types");
        var attributeType = assembly.GetType("Payments.Contracts.PluginMetadataAttribute")!;

        foreach (var (typeName, name) in new[]
        {
            ("Deep.Name.Space.Outer+Inner", "inner"),
            ("Deep.Name.Space.Outer+Middle+Deepest", "deepest"),
            ("class.event", "keyword"),
            ("GlobalPlugin", "global"),
        })
        {
            Assert.True(registry.TryGet(assembly.GetType(typeName, throwOnError: true)!, attributeType, out var metadata));
            Assert.Equal(name, attributeType.GetProperty("Name")!.GetValue(metadata));
        }
    }

